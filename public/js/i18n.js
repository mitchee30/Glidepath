let lang = 'zh';

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'zh';
}

export function getLang() {
  return lang;
}

export function t(key, vars = {}, fallback) {
  const entry = S[key];
  let s = entry ? entry[lang === 'en' ? 1 : 0] : undefined;
  if (s === undefined) {
    if (fallback !== undefined) return fallback;
    console.warn(`[i18n] missing ${key}`);
    return key;
  }
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function hasKey(key) {
  return key in S;
}

const locale = () => (lang === 'en' ? 'en-CA' : 'zh-CN');

export function fmtNum(n, digits = 0) {
  if (n === null || n === undefined || Number.isNaN(n)) return '—';
  return new Intl.NumberFormat(locale(), { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(n);
}

const WEEK = {
  zh: ['周一', '周二', '周三', '周四', '周五', '周六', '周日'],
  en: ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'],
};

export function weekdayShort(i) {
  return WEEK[lang][i];
}

/** style: short (10月18日), long (10月18日 周日), year (2027年4月9日), weekday (周日) */
export function fmtDate(iso, style = 'short') {
  const d = new Date(iso + 'T00:00:00Z');
  const wd = WEEK[lang][(d.getUTCDay() + 6) % 7];
  const m = d.getUTCMonth() + 1;
  const day = d.getUTCDate();
  if (lang === 'zh') {
    if (style === 'weekday') return wd;
    if (style === 'year') return `${d.getUTCFullYear()}年${m}月${day}日`;
    if (style === 'long') return `${m}月${day}日 ${wd}`;
    return `${m}月${day}日`;
  }
  const mon = new Intl.DateTimeFormat('en-CA', { month: 'short', timeZone: 'UTC' }).format(d);
  if (style === 'weekday') return wd;
  if (style === 'year') return `${mon} ${day}, ${d.getUTCFullYear()}`;
  if (style === 'long') return `${wd}, ${mon} ${day}`;
  return `${mon} ${day}`;
}

/** Name for a food entry: table foods follow the UI language, custom ones keep their own name. */
export function foodName(e) {
  const f = e.foodId ? getFood(e.foodId) : null;
  if (f) return lang === 'en' ? f.en : f.zh;
  return e.name || '';
}

